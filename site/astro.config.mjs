import fs from 'node:fs'
import { defineConfig } from 'astro/config'
import starlight from '@astrojs/starlight'
import starlightSidebarTopics from 'starlight-sidebar-topics'
import tailwindcss from '@tailwindcss/vite'
import starlightLlmsTxt from 'starlight-llms-txt'
import starlightMdTxt from 'starlight-md-txt'
import starlightDocSearchTypesense from 'starlight-docsearch-typesense'
import sitemap from '@astrojs/sitemap'

import braverTheme from './src/theme/index.ts'
import { iconsCss } from './src/theme/icons.ts'
import { footer, links, locales, site, title } from './site.config.mjs'
import { topics as generatedTopics, topicMap } from './src/sidebar.generated.mjs'
import { applySidebarOverrides } from './src/sidebar.overrides.mjs'
import { fallbackPaths, privatePaths, privateTitles } from './src/private.generated.mjs'
import { LLMS_PAGE_SEPARATOR, dropPrivatePagesFromLlms } from './src/theme/private-pages.ts'

// Generated sidebar + manual adjustments (sub-pages added outside GitBook).
const topics = applySidebarOverrides(generatedTopics)

// Sidebar and header icons are CSS masks; emit one rule per icon actually used.
const icons = new Set()
const collect = (items) => items.forEach((i) => {
  if (i.attrs?.['data-icon']) icons.add(i.attrs['data-icon'])
  if (i.items) collect(i.items)
})
collect(topics)
fs.mkdirSync('./src/theme/generated', { recursive: true })
fs.writeFileSync('./src/theme/generated/icons.css', `/* generated by astro.config.mjs */\n${iconsCss(icons)}\n`)

// Typesense search when its PUBLIC_TYPESENSE_* variables are set (see typesense/README.md); Pagefind otherwise.
try { process.loadEnvFile() } catch {} // local .env; on Netlify the variables are already in process.env
const env = process.env
const typesense = Boolean(env.PUBLIC_TYPESENSE_HOST && env.PUBLIC_TYPESENSE_SEARCH_KEY && env.PUBLIC_TYPESENSE_COLLECTION)

// Private customer pages: out of the sitemap and LLM files (they also carry noindex and stay out of search).
// "Not translated yet" English copies are left out of the sitemap too. fallbackPaths comes from GitBook,
// so paths that now have an English page written directly in the site (src/content/docs/en/...) are dropped here.
const hasPage = (path) => ['.mdx', '.md', '/index.mdx', '/index.md'].some((ext) => fs.existsSync(`./src/content/docs${path}${ext}`))
const untranslatedPaths = fallbackPaths.filter((path) => !hasPage(path))
const notInSitemap = new Set([...privatePaths, ...untranslatedPaths])
const privatePages = 'guides/private-pages/**'

export default defineConfig({
  site,
  // GitBook URLs have no trailing slash: /guides/foo is served from /guides/foo.html
  trailingSlash: 'never',
  build: { format: 'file' },
  image: { domains: ['cdn.loom.com'] },
  vite: { plugins: [tailwindcss()] },
  integrations: [
    starlight({
      title,
      logo: { light: './src/assets/brand/logo-light.png', dark: './src/assets/brand/logo-dark.png', replacesTitle: true },
      favicon: '/favicon.png',
      defaultLocale: 'root',
      locales,
      lastUpdated: false,
      plugins: [
        braverTheme({ links, footer, search: typesense ? 'typesense' : 'pagefind', css: ['./src/theme/generated/icons.css'] }),
        ...(typesense ? [starlightDocSearchTypesense({ clientOptionsModule: './src/search/typesense.ts' })] : []),
        starlightSidebarTopics(topics, { topics: topicMap }),
        // /llms.txt, /llms-full.txt, /llms-small.txt (default language: French)
        starlightLlmsTxt({
          projectName: 'Braver',
          description: "Centre d'assistance de Braver, la plateforme de communication clinique sécurisée pour les équipes de soins, les patients et leurs proches aidants.",
          customSets: [
            { label: 'Guides', description: 'guides pas-à-pas pour les professionnels, patients, proches aidants et administrateurs', paths: ['guides', 'guides/!(private-pages)/**'] },
            { label: 'Formations', description: 'parcours de formation pour les professionnels et les patients', paths: ['training', 'training/**'] },
            { label: 'Suivi des versions', description: 'notes de version de Braver', paths: ['changelog/**'] },
          ],
          exclude: [privatePages],
          pageSeparator: LLMS_PAGE_SEPARATOR,
          // heading anchor links ("Section intitulée …") are page chrome, not content
          customSelectors: { all: ['.sl-anchor-link'] },
        }),
        // every page as Markdown at <page>.md, like GitBook's Markdown variants
        starlightMdTxt({ format: '.md' }),
      ],
    }),
    // our own sitemap (Starlight then skips its built-in one), with the same i18n settings plus a filter
    sitemap({
      i18n: { defaultLocale: 'root', locales: Object.fromEntries(Object.entries(locales).map(([k, v]) => [k, v.lang])) },
      filter: (page) => !notInSitemap.has(new URL(page).pathname.replace(/\/$/, '') || '/'),
    }),
    dropPrivatePagesFromLlms(privateTitles),
  ],
})
